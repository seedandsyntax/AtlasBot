GLOB_DEP_HIT_CTR: int = 0


class Node:
    def __init__(self, name: str, prior_tracked_countries: list[str]) -> None:
        # print(f"prior_tracked_countries: {prior_tracked_countries}")
        self.name = name
        self.next_ptrs: list[Node]= []
        # print(f"initialized name and next_ptrs: {prior_tracked_countries}")
        self.country_path: list[str] = prior_tracked_countries
        # print(f"initialized country_paths: {self.country_path}")
        self.upd_country_path()
        # print(f"initialized country_paths: {self.country_path}")

    def upd_country_path(self):
        self.country_path.append(self.name)
    
    def next_ptrs_reader(self):
        temp_next_names_in_next_ptrs: list[str] = []
        for next_ptr in self.next_ptrs:
            temp_next_names_in_next_ptrs.append(next_ptr.name)
        # print(", ".join(temp_next_names_in_next_ptrs))

def initial_pos_generation():
    start_positions: list[Node] = []
    for country in countries:
        if country[0] == 's':
            start_positions.append(Node(country, []))
            # start_positions[-1].country_path.append(country)
            print(start_positions[-1].country_path)
    return start_positions

def populate_list(country_node: Node):
    for country in countries:
        if country in country_node.country_path:
            # print(f"{country_node.name} -> {country_node.country_path}")
            continue
        if countries[country][0] == country_node.name[-1]:
            country_node.next_ptrs.append(
                Node(
                    name=country,
                    prior_tracked_countries=country_node.country_path
                )
            )
            # country_node.country_path.append(country)
    # print(country_node.next_ptrs)
    # print(country_node.next_ptrs_reader())

def depth_search(position_set: list[Node]):
    global GLOB_DEP_HIT_CTR
    if len(position_set) == 0:
        GLOB_DEP_HIT_CTR += 1
        print(f"{GLOB_DEP_HIT_CTR} hit, the sequence is: ")
        return
    if GLOB_DEP_HIT_CTR >= 100:
        return
    for country_node in position_set:
        populate_list(country_node=country_node)
        depth_search(country_node.next_ptrs)
        print(f"{' -> '.join(country_node.country_path)}")

